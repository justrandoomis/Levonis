export type RequestStrings = typeof ar;

export const REQUEST_STRINGS: Record<RequestLang, RequestStrings> = { ar, en, ckb };

export function requestLang(lang: string): RequestLang {
  return lang === 'en' || lang === 'ckb' ? lang : 'ar';
}

export function requestStrings(lang: string): RequestStrings {
  return REQUEST_STRINGS[requestLang(lang)];
}

export function useRequestStrings(): RequestStrings {
  const { lang } = useLanguage();
  return requestStrings(lang);
}

/** «{n} يوم» → «3 يوم»; every placeholder the sentence names, in the sentence's own order. */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

/** The reader's word for how an offer is handed over (a closed list; a free-text method from before offers v2 is shown as written). */
export function handoverLabel(method: string, s: RequestStrings): string {
  switch (method) {
    case 'pickup':
      return s.handoverPickup;
    case 'merchant_delivery':
      return s.handoverMerchant;
    case 'courier':
      return s.handoverCourier;
    case '':
      return '—';
    default:
      return method;
  }
}

/** The composer's choices, in the merchant's own voice: «أوصله» · «شركة توصيل» · «استلام». */
export function composerHandover(method: 'pickup' | 'merchant_delivery' | 'courier', s: RequestStrings): string {
  return method === 'pickup' ? s.pickup : method === 'courier' ? s.courier : s.deliverMyself;
}

/** A server-written discussion row, by its code and meta. */
export function systemUpdateLabel(code: string, meta: Record<string, unknown> | null | undefined, s: RequestStrings): string {
  const table = s.system as Record<string, string>;
  const t = table[code];
  if (!t) return code;
  const n = meta && typeof meta.revision === 'number' ? meta.revision : meta && typeof meta.revision === 'string' ? meta.revision : '';
  if (code === 'revised' && n === '') return s.systemRevisedPlain;
  return fill(t, { n });
}

