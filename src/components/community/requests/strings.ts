/**
 * «يوم واحد», «يومان», «3 أيام», «14 يومًا», «100 يوم» — the Arabic noun
 * agrees with its number (the rule of src/components/community/hub/copy.ts:
 * 1, 2, 3–10, 11–99, hundreds); Sorani keeps the singular after a number
 * («٣ ڕۆژ»), English its plural.
 */
export function daysLabel(n: number, lang: RequestLang): string {
  const count = Math.max(0, Math.floor(Number(n) || 0));
  if (lang === 'en') return `${count} ${count === 1 ? 'day' : 'days'}`;
  if (lang === 'ckb') return `${count} ڕۆژ`;
  if (count === 1) return 'يوم واحد';
  if (count === 2) return 'يومان';
  const r = count % 100;
  if (r >= 3 && r <= 10) return `${count} أيام`;
  if (r >= 11 && r <= 99) return `${count} يومًا`;
  return `${count} يوم`;
}

/** «عمل منجز واحد», «عملان منجزان», «5 أعمال منجزة», «12 عملًا منجزًا» — a workshop's finished jobs. */
export function jobsLabel(n: number, lang: RequestLang): string {
  const count = Math.max(0, Math.floor(Number(n) || 0));
  if (lang === 'en') return `${count} ${count === 1 ? 'job done' : 'jobs done'}`;
  if (lang === 'ckb') return `${count} کاری تەواوکراو`;
  if (count === 1) return 'عمل منجز واحد';
  if (count === 2) return 'عملان منجزان';
  const r = count % 100;
  if (r >= 3 && r <= 10) return `${count} أعمال منجزة`;
  if (r >= 11 && r <= 99) return `${count} عملًا منجزًا`;
  return `${count} عمل منجز`;
}

/** «٣ أكتوبر» in the reader's calendar (the app's one date locale rule), or '' for no date. */
export function shortDay(iso: string | null | undefined, lang: RequestLang): string {
  const t = iso ? Date.parse(iso) : NaN;
  if (!Number.isFinite(t)) return '';
  return new Intl.DateTimeFormat(dateLocale(lang), { day: 'numeric', month: 'short' }).format(t);
}

export type OfferTone = 'neutral' | 'success' | 'warning' | 'danger' | 'info';

/** An offer's state in the reader's words and a tone — every state, in all three languages. */
export function offerStateWords(o: { state: string; stale?: boolean; expired?: boolean; draft?: boolean }, s: RequestStrings): { text: string; tone: OfferTone } {
  if (o.draft || o.state === 'draft') return { text: s.stateDraft, tone: 'neutral' };
  if (o.state === 'accepted') return { text: s.stateAccepted, tone: 'success' };
  if (o.state === 'superseded' || (o.state === 'pending' && o.stale)) return { text: s.stateAwaiting, tone: 'warning' };
  if (o.state === 'expired' || o.expired) return { text: s.stateExpired, tone: 'neutral' };
  if (o.state === 'rejected') return { text: s.stateNotChosen, tone: 'neutral' };
  if (o.state === 'withdrawn') return { text: s.stateWithdrawn, tone: 'neutral' };
  return { text: s.stateOpen, tone: 'info' };
}

/** A community order's state as a word (the server's machine word never reaches a reader). */
export function orderStateWord(state: string, s: RequestStrings): string {
  const table = s.orderStates as Record<string, string>;
  return table[state] ?? s.orderStates.in_progress;
}

/** The escrow's state as the sentence the money line says — held, released, returned; never a key or an id. */
export function escrowSentence(state: string | null | undefined, s: RequestStrings): string {
  switch (state) {
    case 'held':
      return s.escrowHeld;
    case 'released':
      return s.escrowReleased;
    case 'refunded':
      return s.escrowRefunded;
    case 'partially_refunded':
      return s.escrowPartial;
    case 'disputed':
      return s.escrowDisputed;
    case 'cancelled':
      return s.escrowCancelled;
    default:
      return s.escrowPending;
  }
}

/**
 * `fill` for a sentence that carries an ELEMENT — «كان {price}» with the
 * price drawn as <Money>: the template is split on its placeholders and each
 * is replaced by its node, in the sentence's own order, so no language's word
 * order is assembled from fragments.
 */
export function fillNodes(template: string, values: Record<string, ReactNode>): ReactNode[] {
  return template.split(/(\{\w+\})/).map((part, i) => {
    const m = /^\{(\w+)\}$/.exec(part);
    return createElement(Fragment, { key: i }, m && m[1] in values ? values[m[1]] : part);
  });
}
