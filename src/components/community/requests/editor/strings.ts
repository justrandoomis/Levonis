/**
 * «قطعتان», «3 قطع», «2 parts», «3 پارچە» — the header of a job of parts, in
 * the cards' own word. Arabic agrees with its number (dual, 3–10, 11+).
 */
export function partsCountWords(n: number, lang: EditorLang): string {
  if (lang === 'en') return n === 1 ? '1 part' : `${n} parts`;
  if (lang === 'ckb') return `${n} پارچە`;
  if (n === 1) return 'قطعة واحدة';
  if (n === 2) return 'قطعتان';
  if (n >= 3 && n <= 10) return `${n} قطع`;
  return `${n} قطعة`;
}

/** «3 نسخ في الطقم» — the pieces of one set, said only when a part is made more than once a set. */
export function piecesPerSetWords(k: number, lang: EditorLang): string {
  if (lang === 'en') return k === 1 ? '1 copy in a set' : `${k} copies in a set`;
  if (lang === 'ckb') return `${k} دانە لە هەر سێتێکدا`;
  if (k === 1) return 'نسخة واحدة في الطقم';
  if (k === 2) return 'نسختان في الطقم';
  if (k >= 3 && k <= 10) return `${k} نسخ في الطقم`;
  return `${k} نسخة في الطقم`;
}

/** «2 أطقم» when the sets are more than one. */
export function setsWords(s: number, lang: EditorLang): string {
  if (lang === 'en') return s === 1 ? '1 set' : `${s} sets`;
  if (lang === 'ckb') return `${s} سێت`;
  if (s === 1) return 'طقم واحد';
  if (s === 2) return 'طقمان';
  if (s >= 3 && s <= 10) return `${s} أطقم`;
  return `${s} طقمًا`;
}
