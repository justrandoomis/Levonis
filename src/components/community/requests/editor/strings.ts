export const EDITOR_STRINGS: Record<EditorLang, EditorStrings> = { ar, en, ckb };

export function editorLang(lang: string): EditorLang {
  return lang === 'en' || lang === 'ckb' ? lang : 'ar';
}

export function editorStrings(lang: string): EditorStrings {
  return EDITOR_STRINGS[editorLang(lang)];
}

