/**
 * PRUSASLICER CLI.
 *
 *   prusa-slicer --export-gcode --merge
 *     --load <printer.ini> --load <print.ini> --load <filament.ini>
 *     --gcode-label-objects disabled
 *     --layer-height 0.2 --fill-density 15% --perimeters 2
 *     --support-material --support-material-auto [--support-material-style organic] | --no-support-material
 *     --brim-width <mm> | --brim-width 0
 *     --output <work>/out/lv_<job>.gcode
 *     <model> <model> …                     (each model × quantity × copies)
 *
 * `--merge` puts every object of the job on ONE plate, arranged by
 * PrusaSlicer. Without it each input file is a separate print exported to the
 * same --output, so only the last one survived: a quantity-5 job was quoted
 * and printed as one object (checked with PrusaSlicer 2.7.2).
 *
 * `--gcode-label-objects disabled` wins over the workshop's profile: object
 * names come from the customer's 3MF and PrusaSlicer writes them unescaped
 * into its label lines (`; printing object <name>`, `M486 A<name>`) — a
 * newline in a name would start a printer command (2.7.2: `M211 S0` arrived
 * as its own line). With labels off no name reaches the G-code.
 *
 * THE PLATE CHECK (prusaPlateProblem). PrusaSlicer does not refuse merged
 * objects that do not fit one bed: 2.7 writes them BESIDE the bed (exit 0, no
 * warning: two 200 × 150 mm plates on a 250 × 210 bed reached X 531), and 2.9
 * arranges onto further beds and slices only the first, leaving the rest out
 * (its source: with_single_bed_model_fff(model, 0), instances not fully
 * inside dropped — not run here). So the produced file is checked: every
 * extruding move of the print itself (not the ;TYPE:Custom start and end
 * G-code, where purge lines run outside the print area) must lie on the bed
 * the file states (`; bed_shape = …`), or OBJECTS_DO_NOT_FIT_ONE_PLATE. A
 * PrusaSlicer of 2.9 or later slicing more than one object is refused with
 * PLATE_UNVERIFIABLE: with labels off nothing in the file counts the objects,
 * so a left-out one could not be seen.
 *
 * v1 limits, refused with a code rather than sliced differently: one
 * filament per job (MULTI_MATERIAL_UNSUPPORTED — per-object extruders need a
 * project file), and no automatic orientation (AUTO_ORIENTATION_UNSUPPORTED —
 * the CLI has none). PrusaSlicer reports 0 g for a filament profile without a
 * density; gcode.mjs then refuses the weight as unknown.
 */
import { createReadStream, existsSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { createInterface } from 'node:readline';

const fail = (error_code, detail) => ({ ok: false, error_code, detail });

/** How far past the stated bed an extrusion may lie before the plate is refused (a brim or skirt at the edge). */
const BED_TOLERANCE_MM = 10;
const NUMBER = '(-?\\d*\\.?\\d+)';
const AXIS = (k) => new RegExp(`${k}${NUMBER}`);

/**
 * Is the produced G-code the whole job on one bed? Null when it is, else the
 * refusal: `{ code, detail }` (see the header).
 * @param {string} path  the G-code file
 * @param {number} objects  the objects the plan put on the plate
 * @returns {Promise<{ code: 'OBJECTS_DO_NOT_FIT_ONE_PLATE' | 'PLATE_UNVERIFIABLE', detail: string } | null>}
 */
export async function prusaPlateProblem(path, objects) {
  let version = null;
  let bed = null;
  let type = null;
  let relativeE = false;
  let e = 0;
  let x = null;
  let y = null;
  let lineNo = 0;
  const ext = { minX: Infinity, maxX: -Infinity, minY: Infinity, maxY: -Infinity };
  const rl = createInterface({ input: createReadStream(path), crlfDelay: Infinity });
  for await (const raw of rl) {
    lineNo++;
    const line = raw.trimEnd();
    let m;
    if (lineNo === 1 && (m = /^; generated by PrusaSlicer (\d+)\.(\d+)\.\d+/.exec(line))) version = [Number(m[1]), Number(m[2])];
    if (line.startsWith(';TYPE:')) {
      type = line.slice(6);
      continue;
    }
    if (line.startsWith('; bed_shape = ')) {
      const points = line.slice(14).split(',').map((pt) => pt.split('x').map(Number));
      if (points.length >= 3 && points.every((pt) => pt.length === 2 && pt.every(Number.isFinite))) {
        bed = { minX: Math.min(...points.map((pt) => pt[0])), maxX: Math.max(...points.map((pt) => pt[0])), minY: Math.min(...points.map((pt) => pt[1])), maxY: Math.max(...points.map((pt) => pt[1])) };
      }
      continue;
    }
    if (line.charCodeAt(0) === 59 /* ; */) continue;
    const code = line.split(';')[0];
    if (/^M83\b/.test(code)) relativeE = true;
    else if (/^M82\b/.test(code)) relativeE = false;
    else if (/^G92\b/.test(code)) {
      const reset = AXIS('E').exec(code);
      if (reset) e = Number(reset[1]);
    } else if (/^G[0-3]\b/.test(code)) {
      const mx = AXIS('X').exec(code);
      const my = AXIS('Y').exec(code);
      const me = AXIS('E').exec(code);
      if (mx) x = Number(mx[1]);
      if (my) y = Number(my[1]);
      let extruding = false;
      if (me) {
        const v = Number(me[1]);
        extruding = relativeE ? v > 0 : v > e;
        if (!relativeE) e = v;
      }
      // Only the print itself: the start and end G-code (;TYPE:Custom, and anything before the first type) purge where they like.
      if (extruding && (mx || my) && x !== null && y !== null && type !== null && type !== 'Custom') {
        ext.minX = Math.min(ext.minX, x);
        ext.maxX = Math.max(ext.maxX, x);
        ext.minY = Math.min(ext.minY, y);
        ext.maxY = Math.max(ext.maxY, y);
      }
    }
  }
  if (objects > 1 && (!version || version[0] > 2 || (version[0] === 2 && version[1] >= 9))) {
    return {
      code: 'PLATE_UNVERIFIABLE',
      detail: `${version ? `PrusaSlicer ${version.join('.')}` : 'a PrusaSlicer that does not sign the file'} may leave objects that miss the first bed out of the G-code, and with object labels off nothing in the file counts the job's ${objects} objects`,
    };
  }
  if (!bed) return { code: 'PLATE_UNVERIFIABLE', detail: 'the G-code states no bed_shape: the plate cannot be checked' };
  if (ext.minX === Infinity) return { code: 'PLATE_UNVERIFIABLE', detail: 'the G-code extrudes nothing outside its custom start and end G-code' };
  const off =
    ext.minX < bed.minX - BED_TOLERANCE_MM || ext.maxX > bed.maxX + BED_TOLERANCE_MM || ext.minY < bed.minY - BED_TOLERANCE_MM || ext.maxY > bed.maxY + BED_TOLERANCE_MM;
  return off
    ? { code: 'OBJECTS_DO_NOT_FIT_ONE_PLATE', detail: `the print spans X ${ext.minX}..${ext.maxX}, Y ${ext.minY}..${ext.maxY} on a bed of X ${bed.minX}..${bed.maxX}, Y ${bed.minY}..${bed.maxY}` }
    : null;
}

/** The argument list (pure: tested on its own). */
export function prusaArgs({ printerIni, printIni, filamentIni, settings, brimWidthMm, outPath, objectPaths }) {
  const args = ['--export-gcode', '--merge', '--load', printerIni, '--load', printIni, '--load', filamentIni, '--gcode-label-objects', 'disabled'];
  const overrides = {};
  if (Number.isInteger(settings.layer_height_um)) overrides['layer-height'] = String(settings.layer_height_um / 1000);
  if (Number.isInteger(settings.infill_percent)) overrides['fill-density'] = `${settings.infill_percent}%`;
  if (Number.isInteger(settings.walls)) overrides.perimeters = String(settings.walls);
  for (const [k, v] of Object.entries(overrides)) args.push(`--${k}`, v);
  if (settings.supports === 'none') args.push('--no-support-material');
  else if (settings.supports) {
    args.push('--support-material', '--support-material-auto');
    if (settings.supports === 'tree') args.push('--support-material-style', 'organic');
  }
  if (typeof settings.brim === 'boolean') args.push('--brim-width', settings.brim ? String(brimWidthMm) : '0');
  args.push('--output', outPath, ...objectPaths);
  return { args, overrides: { ...overrides, supports: settings.supports ?? null, brim: settings.brim ?? null, gcode_label_objects: 'disabled' } };
}

export const prusa = {
  label: 'PrusaSlicer',
  layerMarkers: [';LAYER_CHANGE'],

  async command({ plan, files, workDir, outBase, cfg }) {
    if (plan.slots.length > 1) return fail('MULTI_MATERIAL_UNSUPPORTED', 'the PrusaSlicer CLI path slices one filament per job');
    if (plan.orientation === 'auto') return fail('AUTO_ORIENTATION_UNSUPPORTED', 'the PrusaSlicer CLI has no automatic orientation');
    const outDir = join(workDir, 'out');
    await mkdir(outDir, { recursive: true });
    const { args, overrides } = prusaArgs({
      printerIni: plan.machine.machine,
      printIni: plan.machine.process,
      filamentIni: plan.slots[0].profile,
      settings: plan.settings,
      brimWidthMm: cfg.brim_width_mm ?? 5,
      outPath: join(outDir, `${outBase}.gcode`),
      objectPaths: plan.objects.map((o) => files.get(o.file_id)),
    });
    return { ok: true, args, overrides };
  },

  async output({ plan, workDir, outBase }) {
    const p = join(workDir, 'out', `${outBase}.gcode`);
    if (!existsSync(p)) return null;
    const problem = await prusaPlateProblem(p, plan.objects.length);
    return problem ? { error_code: problem.code, detail: problem.detail } : { path: p, format: 'gcode' };
  },
};
