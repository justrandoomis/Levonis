export function tr(loc: Locale, key: string, vars: Record<string, string | number> = {}): string {
  const template = ASSIST_T[loc][key] ?? ASSIST_T.ar[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] === undefined ? `{${k}}` : String(vars[k])));
}
